"""Native binary archive check using synthetic points and an isolated folder.

Loads the real calibration only to exercise its streaming hash and metadata.
No DUT scan, network connection, real upload queue or cloud credentials are
used. Set ARCHIVE_STRESS_POINTS=4096 before exec to include the optional stress
case; the default is a quick two-point transaction/integrity check.
"""

from machine import Pin

Pin(20, Pin.OUT, value=0)
Pin(21, Pin.OUT, value=0)

import gc
import hashlib
import binascii
import json
import os
import struct
import time
from hardware import Instrument
from archive import Archive, UploadSource, COLUMNS, RECORD_BYTES, FOOTER_FORMAT, FOOTER_BYTES
from cloud import CloudManager
import model
import storage


class DriveGuard:
    def __init__(self, instrument):
        self.instrument = instrument
        self.commands = 0

    def set_duty(self, role, duty):
        self.commands += 1
        raise RuntimeError("Unexpected drive during archive verification")

    def zero(self):
        self.instrument.zero()


class MemoryConfig:
    def load_json(self, path):
        assert path == "__memory_cloud_config", "Unexpected configuration access"
        return {"version": 1, "enabled": True,
                "url": "https://script.google.com/macros/s/SYNTHETIC_TEST_ONLY/exec"}

    def save_json_atomic(self, path, data):
        raise RuntimeError("Archive diagnostic must not save cloud configuration")


class MockAcknowledgement:
    def __init__(self):
        self.started = False
        self.answer = None

    def start(self, url, path, scan_id, sha256, point_count):
        self.started = True
        self.answer = {"ok": True, "scan_id": scan_id, "sha256": sha256,
                       "point_count": point_count}

    def step(self):
        return self.answer

    def close(self):
        pass


def hex_digest(digest):
    return binascii.hexlify(digest.digest()).decode()


def scan_settings(count):
    result = dict(model.DEFAULT_SETTINGS)
    result.update({"driver_supply_uv": 5000000, "source_voltage_uv": 0,
                   "drain_start_uv": 0, "drain_stop_uv": (count - 1) * 1000,
                   "drain_step_uv": 1000, "gate_start_uv": 0,
                   "gate_stop_uv": 0, "gate_step_uv": 500000})
    return result


def synthetic_point(index):
    return {"index": index, "curve": 0,
            "requested_vds": index * 0.001, "requested_vgs": 0.0,
            "vds": index * 0.001 + 0.000123456, "vgs": 0.00123456,
            "id_a": 0.000190123456, "ig_a": -0.0000000123456789,
            "id_std_a": 0.000000123, "ig_std_a": 0.000000000245,
            "drain_shunt_v": 0.00138, "gate_shunt_v": 0.00456789,
            "drain_shunt_std_v": 0.0000025, "gate_shunt_std_v": 0.00000175,
            "batches_completed": model.DEFAULT_SETTINGS["batches"],
            "drain_voltage_limited": False, "gate_voltage_limited": True}


def stream_check(path, expected, read_size=1024, collect=False):
    source = UploadSource(path)
    digest, length = hashlib.sha256(), 0
    payload = bytearray() if collect else None
    try:
        assert source.point_count == expected["point_count"]
        while True:
            part = source.read(read_size)
            if not part:
                break
            assert len(part) <= read_size
            digest.update(part)
            length += len(part)
            if payload is not None:
                payload.extend(part)
        assert source.size == length == expected["wire_size"]
        assert hex_digest(digest) == expected["sha256"], "Wire hash changed"
        return payload
    finally:
        source.close()


def reserve_probe_directory():
    for unused in range(8):
        name = "__archive_probe_%x_%s" % (time.ticks_ms(), binascii.hexlify(os.urandom(2)).decode())
        try:
            os.stat(name)
        except OSError as error:
            if error.args and error.args[0] == 2:
                return name
            raise
    raise RuntimeError("A fresh archive probe directory could not be created")


def cleanup_probe(directory, identifiers):
    # Only exact filenames generated by this run may be removed. Never recurse,
    # inspect the real scans directory, or remove an unexpected leftover file.
    assert directory.startswith("__archive_probe_") and "/" not in directory and "\\" not in directory
    for scan_id in identifiers:
        assert scan_id.startswith("a11ce-")
        assert all(character in "0123456789abcdef-" for character in scan_id)
        for suffix in (".writing", ".draft", ".pending", ".sent", ".meta", ".meta.tmp"):
            path = directory + "/" + scan_id + suffix
            try:
                os.remove(path)
            except OSError as error:
                if not error.args or error.args[0] != 2:
                    raise
    try:
        os.rmdir(directory)
    except OSError as error:
        if not error.args or error.args[0] != 2:
            raise


hardware = Instrument()
probe, directory, manager = None, None, None
created = []
started = time.ticks_ms()
report = {}
try:
    guard = DriveGuard(hardware)
    guard.zero()
    calibration = storage.load_json("calibration.json")
    assert isinstance(calibration, dict), "A calibration is required for the hash test"
    directory = reserve_probe_directory()
    probe = Archive(directory=directory, device_id="a11ce")
    scan_id = probe.begin_scan(scan_settings(2), calibration, time.ticks_ms())
    created.append(scan_id)
    for index in range(2):
        probe.record_point(synthetic_point(index))
    metadata = probe.finish_scan(time.ticks_ms())
    assert probe.pending_count == 0, "Unaccepted scan was queued"
    assert probe.accept_scan() == scan_id and probe.pending_count == 1
    entry = probe.next_pending()
    payload = stream_check(entry["path"], metadata, read_size=37, collect=True)
    decoded = json.loads(payload.decode())
    assert decoded["columns"] == COLUMNS and decoded["point_count"] == 2
    assert decoded["outcome"] == "complete" and decoded["created_utc"] is None
    assert len(decoded["points"]) == 2
    assert decoded["points"][1][0] == 1 and decoded["points"][1][-1] is True
    assert abs(decoded["points"][0][6] - synthetic_point(0)["id_a"]) < 0.000000001
    assert decoded["calibration"]["metadata"] == calibration.get("metadata", {})
    binary_bytes = os.stat(entry["path"])[6]
    with open(entry["path"], "rb") as stream:
        stream.seek(binary_bytes - FOOTER_BYTES)
        footer = struct.unpack(FOOTER_FORMAT, stream.read(FOOTER_BYTES))
    # The footer is two unsigned32 values (64 bits total), not a uint64 epoch.
    assert struct.calcsize(FOOTER_FORMAT) == FOOTER_BYTES == 8
    assert footer[0] == 2 and footer[1] >= 0
    assert struct.unpack(FOOTER_FORMAT, struct.pack(FOOTER_FORMAT, 4096, 0xffffffff))[1] == 0xffffffff
    del decoded, payload
    gc.collect()
    reopened = Archive(directory=directory, device_id="a11ce")
    assert reopened.pending_count == 1
    assert reopened.next_pending()["sha256"] == metadata["sha256"]
    stream_check(reopened.next_pending()["path"], metadata)

    # Cancelling an incomplete draft cannot alter a previously accepted scan.
    draft_id = probe.begin_scan(scan_settings(2), calibration, time.ticks_ms())
    created.append(draft_id)
    probe.record_point(synthetic_point(0))
    probe.discard_scan()
    assert probe.pending_count == 1 and probe.next_pending()["scan_id"] == scan_id
    stream_check(probe.next_pending()["path"], metadata)
    transport = MockAcknowledgement()
    manager = CloudManager(archive=probe, transport=transport, store=MemoryConfig(),
                           path="__memory_cloud_config")
    manager.tick(time.ticks_ms(), online=True, safe=True)
    assert transport.started and probe.pending_count == 1
    manager.tick(time.ticks_ms(), online=True, safe=True)
    assert probe.pending_count == 0 and probe.saved_count == 1
    report.update({"two_point_roundtrip": True, "wire_hash_and_length_match": True,
                   "reopen_preserved_queue": True, "cancel_preserved_pending": True,
                   "mock_ack_marked_sent": True, "footer_64_bits_verified": True,
                   "binary_bytes": binary_bytes, "wire_bytes": metadata["wire_size"]})

    stress_count = globals().get("ARCHIVE_STRESS_POINTS", 0)
    assert stress_count in (0, 4096), "Stress size must be zero or4096"
    if stress_count:
        gc.collect()
        minimum_free = gc.mem_free()
        stress_started = time.ticks_ms()
        stress_id = probe.begin_scan(scan_settings(stress_count), calibration, stress_started)
        created.append(stress_id)
        for index in range(stress_count):
            probe.record_point(synthetic_point(index))
            if (index + 1) % 256 == 0:
                minimum_free = min(minimum_free, gc.mem_free())
                print("ARCHIVE_STRESS_PROGRESS", index + 1, stress_count)
                gc.collect()
        stress = probe.finish_scan(time.ticks_ms())
        assert probe.accept_scan() == stress_id
        path = probe.next_pending()["path"]
        stress_bytes = os.stat(path)[6]
        assert stress_bytes < 226000 and RECORD_BYTES == 54
        assert stress["wire_size"] < 2 * 1024 * 1024
        stream_check(path, stress)
        report.update({"stress_points": stress_count, "stress_binary_bytes": stress_bytes,
                       "stress_wire_bytes": stress["wire_size"], "stress_hash_match": True,
                       "stress_elapsed_ms": time.ticks_diff(time.ticks_ms(), stress_started),
                       "min_observed_free_bytes": minimum_free})
    assert guard.commands == 0
    report.update({"outputs_never_driven": True, "no_network_used": True,
                   "elapsed_ms": time.ticks_diff(time.ticks_ms(), started)})
finally:
    try:
        hardware.close()
    finally:
        Pin(20, Pin.OUT, value=0)
        Pin(21, Pin.OUT, value=0)
    if manager is not None:
        manager.pause()
    if probe is not None:
        if probe._current is not None and probe._current not in created:
            created.append(probe._current)
        probe.discard_scan()
    if directory is not None:
        cleanup_probe(directory, created)
    print("OUTPUTS_DISABLED")

report["probe_files_removed"] = True
gc.collect()
report["free_heap_bytes"] = gc.mem_free()
print("ARCHIVE_NATIVE_TEST", json.dumps(report))
